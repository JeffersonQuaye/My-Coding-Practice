//For Loop
for (let i = 0; i <= 5; i ++) {
    console.log(i, 'Hello World');   
}

console.log('------------------');

//While Loop
let j = 0;
while (j <= 5) {
    console.log(j, 'Hello World');
    j++
}

console.log('------------------');

//Do-While Loop
let k = 0;
do {
    console.log(k, 'Hello World');
    k++
} while (k <= 5);